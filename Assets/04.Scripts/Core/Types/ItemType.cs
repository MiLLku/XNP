/// <summary>
/// 아이템 종류 식별자.
///
/// 정수값 규칙:
///   - 0          : None (없음)
///   - 1 ~ 100    : 원자재 (Raw Materials) — 채광·벌목 등으로 직접 획득
///   - 101 ~ 200  : 가공 자원 (Processed) — 제련·제작 등으로 만들어짐
///   - 201 ~ 250  : 음식 (Food) — 직원이 섭취해 배고픔 회복
///   - 251 ~ 300  : 약물 (Drug) — 직원이 복용해 재미 회복
///   - 301 ~ 350  : 무기 (Weapon) — 장비 (EquipmentData 연동)
///   - 351 ~ 400  : 방어구 (Armor) — 장비 (EquipmentData 연동)
///   - 401 ~      : 향후 확장 (도구·부품 등)
///
/// 정수값은 SaveSystem과 외부 통신에서 사용됩니다. 한 번 정한 값은 가급적 바꾸지 마세요
/// (저장 파일 호환성이 깨집니다).
/// </summary>
public enum ItemType
{
    None = 0,

    // ─── 원자재 (1~100) ──────────────────────────
    Dirt      = 1,
    Stone     = 2,
    IronOre   = 3,
    CopperOre = 4,
    SilverOre = 5,
    GoldOre   = 6,
    Wood      = 7,

    // ─── 가공 자원 (101~200) ────────────────────
    IronIngot   = 101,
    CopperIngot = 102,
    SilverIngot = 103,
    GoldIngot   = 104,

    // ─── 음식 (201~250) ─────────────────────────
    Berry       = 201,

    // ─── 약물 (251~300) ─────────────────────────
    Sedative    = 251,

    // ─── 무기 (301~350) ─────────────────────────
    IronSword   = 301,

    // ─── 방어구 (351~400) ───────────────────────
    IronArmor   = 351,
}
